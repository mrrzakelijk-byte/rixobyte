function runPreloader() {
  if (!preloader) return;
  const fill = preloader.querySelector(".preloader-fill");
  const percent = preloader.querySelector(".preloader-percent");

  if (prefersReducedMotion) {
    document.body.classList.remove("is-loading");
    document.body.classList.add("site-ready");
    return;
  }

  let value = 0;
  const finish = () => {
    document.body.classList.remove("is-loading");
    document.body.classList.add("site-ready");
  };

  const tick = () => {
    value = Math.min(100, value + Math.random() * 14 + 4);
    if (fill) fill.style.width = `${value}%`;
    if (percent) percent.textContent = `${Math.round(value)}%`;
    if (value < 100) {
      window.setTimeout(tick, 90);
    } else {
      window.setTimeout(finish, 260);
    }
  };

  window.setTimeout(tick, 200);
}

function setupScrollProgress() {
  if (!scrollProgress) return;
  let ticking = false;

  const update = () => {
    const scrollTop = window.scrollY || document.documentElement.scrollTop;
    const docHeight = document.documentElement.scrollHeight - window.innerHeight;
    const ratio = docHeight > 0 ? (scrollTop / docHeight) * 100 : 0;
    scrollProgress.style.width = `${Math.min(100, Math.max(0, ratio))}%`;
    ticking = false;
  };

  window.addEventListener("scroll", () => {
    if (!ticking) {
      window.requestAnimationFrame(update);
      ticking = true;
    }
  });

  update();
}

