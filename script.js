function setupTiltGlare() {
  tiltCards.forEach((card) => {
    card.addEventListener("mousemove", (event) => {
      const rect = card.getBoundingClientRect();
      const mx = ((event.clientX - rect.left) / rect.width) * 100;
      const my = ((event.clientY - rect.top) / rect.height) * 100;
      card.style.setProperty("--mx", `${mx}%`);
      card.style.setProperty("--my", `${my}%`);
    });
  });
}

function setupHeroParallax() {
  if (!heroVisual || prefersReducedMotion) return;

  heroVisual.addEventListener("mousemove", (event) => {
    const rect = heroVisual.getBoundingClientRect();
    const x = (event.clientX - rect.left) / rect.width - 0.5;
    const y = (event.clientY - rect.top) / rect.height - 0.5;
    const rotateX = y * -34;
    const rotateY = x * 38;
    heroVisual.style.transform = `rotateX(${rotateX}deg) rotateY(${rotateY}deg) scale3d(1.03, 1.03, 1.03)`;
  });

  heroVisual.addEventListener("mouseleave", () => {
    heroVisual.style.transform = "rotateX(0deg) rotateY(0deg) scale3d(1,1,1)";
  });
}

function scrambleElement(element) {
  const original = element.dataset.originalText || element.textContent;
  element.dataset.originalText = original;
  if (element.dataset.scrambling === "true") return;
  element.dataset.scrambling = "true";

  const letters = original.split("");
  let iteration = 0;
  const totalSteps = letters.length + 6;

  const interval = window.setInterval(() => {
    element.textContent = letters
      .map((letter, index) => {
        if (letter === " ") return " ";
        if (index < iteration) return letters[index];
        return SCRAMBLE_CHARS[Math.floor(Math.random() * SCRAMBLE_CHARS.length)];
      })
      .join("");

    iteration += 1;
    if (iteration >= totalSteps) {
      window.clearInterval(interval);
      element.textContent = original;
      element.dataset.scrambling = "false";
    }
  }, 28);
}

function setupScrambleText() {
  if (prefersReducedMotion) return;
  scrambleTargets.forEach((element) => {
    element.addEventListener("mouseenter", () => scrambleElement(element));
  });
}

function setupHero3D() {
  if (!heroCanvas || typeof THREE === "undefined" || prefersReducedMotion) return;

  let renderer;
  try {
    renderer = new THREE.WebGLRenderer({ canvas: heroCanvas, alpha: true, antialias: true });
  } catch (error) {
    return;
  }

  const scene = new THREE.Scene();
  scene.fog = new THREE.Fog(0x0d1713, 4, 9);
  const camera = new THREE.PerspectiveCamera(45, 1, 0.1, 100);
  camera.position.z = 6;
  renderer.setPixelRatio(Math.min(window.devicePixelRatio || 1, 2));

  const group = new THREE.Group();
  scene.add(group);

  const green = 0x25c96f;
  const cageGeometry = new THREE.IcosahedronGeometry(2.1, 0);
  const cageMaterial = new THREE.MeshBasicMaterial({ color: green, wireframe: true, transparent: true, opacity: 0.4 });
  const cage = new THREE.Mesh(cageGeometry, cageMaterial);
  group.add(cage);

  const logoTexture = new THREE.TextureLoader().load("rixobyte-logo.png");
  const logoMaterial = new THREE.MeshBasicMaterial({ map: logoTexture, transparent: true, side: THREE.DoubleSide });
  const logoGeometry = new THREE.PlaneGeometry(1.9, 1.9);
  const logoPlane = new THREE.Mesh(logoGeometry, logoMaterial);
  group.add(logoPlane);

  const particleGeometry = new THREE.BufferGeometry();
  const particleCount = 80;
  const positions = new Float32Array(particleCount * 3);
  for (let i = 0; i < particleCount * 3; i += 1) {
    positions[i] = (Math.random() - 0.5) * 9;
  }
  particleGeometry.setAttribute("position", new THREE.BufferAttribute(positions, 3));
  const particleMaterial = new THREE.PointsMaterial({ color: green, size: 0.04, transparent: true, opacity: 0.55 });
  const particles = new THREE.Points(particleGeometry, particleMaterial);
  group.add(particles);

  let targetX = 0;
  let targetY = 0;
  let frameId = null;
  let isVisible = true;

  function resize() {
    if (!heroCanvas.parentElement) return;
    const { clientWidth, clientHeight } = heroCanvas.parentElement;
    if (!clientWidth || !clientHeight) return;
    renderer.setSize(clientWidth, clientHeight, false);
    camera.aspect = clientWidth / clientHeight;
    camera.updateProjectionMatrix();
  }

  function animate() {
    if (!isVisible) return;
    cage.rotation.x += 0.006;
    cage.rotation.y += 0.009;
    logoPlane.rotation.y += 0.018;
    particles.rotation.y += 0.0018;
    group.rotation.y += (targetX - group.rotation.y) * 0.06;
    group.rotation.x += (targetY - group.rotation.x) * 0.06;
    renderer.render(scene, camera);
    frameId = window.requestAnimationFrame(animate);
  }

  heroVisual?.addEventListener("mousemove", (event) => {
    const rect = heroVisual.getBoundingClientRect();
    targetX = ((event.clientX - rect.left) / rect.width - 0.5) * 1.4;
    targetY = ((event.clientY - rect.top) / rect.height - 0.5) * -1.4;
  });

  if ("IntersectionObserver" in window) {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          isVisible = entry.isIntersecting;
          if (isVisible && !frameId) animate();
        });
      },
      { threshold: 0.05 }
    );
    observer.observe(heroCanvas);
  }

  window.addEventListener("resize", resize);
  resize();
  animate();
}

function updateActiveNav() {
  const currentPath = window.location.pathname.split("/").pop() || "index.html";
  navLinks.forEach((link) => {
    const href = link.getAttribute("href") || "";
    if (currentPath === "info.html") {
      link.classList.toggle("active", href.includes("info.html"));
    } else if (href === "#top" || href === "index.html#top") {
      link.classList.add("active");
    }
  });
}

